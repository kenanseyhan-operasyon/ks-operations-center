import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {newEntity} from '../src/scene-data';
import {FacilityNetwork} from '../src/facility-network';
import {MonitorPanel} from '../src/monitor-panel';
import {makeObject} from '../src/objects';
import {localToWorld} from '../src/facility-data';
const dom=new JSDOM('<!doctype html><body/>',{url:'https://ks-3d-test.onrender.com/'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,HTMLInputElement:dom.window.HTMLInputElement,HTMLTextAreaElement:dom.window.HTMLTextAreaElement});
const host=document.createElement('section'),stage=document.createElement('div');stage.id='wsStage';stage.tabIndex=0;host.append(stage);document.body.append(host);
const source=newEntity('WATER_SOURCE',0,1),monitor=newEntity('FIRE_MONITOR',0,0);
monitor.facility={supplyId:source.id,open:true};
const person=newEntity('NATHAN_OPERATOR',0,-1);person.position=localToWorld(monitor,[0,0,-1]);
const scene=[source,monitor,person],network=new FacilityNetwork();network.start(scene);
const model=makeObject(monitor);
assert.ok(model.getObjectByName('MONITOR_GRIP_LEFT')&&model.getObjectByName('MONITOR_GRIP_RIGHT'),'actual rendered monitor yoke must contain both hand grips');
assert.ok(model.getObjectByName('MONITOR_STREAM'),'actual rendered monitor must include a movable stream');
const panel=new MonitorPanel(host,network,()=>scene,()=>person);
assert.ok(panel.open(monitor),'Nathan can open fire monitor after reaching rear yoke');
assert.equal(panel.aimingMonitorId,monitor.id,'mouse aiming must start immediately upon reaching controls');
assert.equal(stage.style.cursor,'crosshair');
assert.equal(panel.grippingMonitorId,monitor.id,'TUT command engages real monitor hand-hold state');
const holdButton=host.querySelector<HTMLButtonElement>('[data-grip]')!;
assert.ok(holdButton,'Explicit TUT/BIRAK operator command is visible');
holdButton.click();
assert.equal(panel.grippingMonitorId,undefined,'BIRAK releases the physical hand-hold');
assert.equal(panel.aimingMonitorId,undefined,'BIRAK also stops accidental mouse steering');
assert.equal(stage.style.cursor,'');
holdButton.click();
assert.equal(panel.grippingMonitorId,monitor.id,'TUT restores physical monitor hold');
host.querySelector<HTMLButtonElement>('[data-aim]')!.click();
assert.equal(panel.aimingMonitorId,monitor.id,'Mouse control activates only after TUT');

const pointer=(type:string,x:number,y:number)=>{const ev=new dom.window.MouseEvent(type,{bubbles:true,cancelable:true,button:0,clientX:x,clientY:y});Object.defineProperty(ev,'pointerId',{value:5});stage.dispatchEvent(ev);};
pointer('pointerdown',100,100);pointer('pointermove',170,60);pointer('pointerup',170,60);
assert.ok(network.monitor(monitor.id).yaw>15,'drag rotates yaw');
assert.ok(network.monitor(monitor.id).elevation>35,'drag raises nozzle');
stage.dispatchEvent(new dom.window.WheelEvent('wheel',{bubbles:true,cancelable:true,deltaY:120}));
assert.ok(network.monitor(monitor.id).opening<1,'wheel controls nozzle aperture');
const before=network.states.get(monitor.id)?.flowing;
host.querySelector<HTMLButtonElement>('[data-water]')!.click();
assert.notEqual(network.states.get(monitor.id)?.flowing,before,'discharge on/off button operates monitor valve');
panel.close();assert.equal(panel.aimingMonitorId,undefined);assert.equal(stage.style.cursor,'');
console.log('PASS actual 3D monitor model, automatic grip-ready aiming, mouse drag, wheel flow and water toggle');
dom.window.close();

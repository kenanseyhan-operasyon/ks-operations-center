import * as T from 'three';
import assert from 'node:assert/strict';
import {newEntity} from '../src/scene-data';
import {FacilityNetwork} from '../src/facility-network';
import {defaultMonitor,monitorTrajectory,behindMonitor,aimMonitorByDrag,adjustMonitorOpening,canGripMonitor,prepareMonitor} from '../src/monitor-training';
import {localToWorld} from '../src/facility-data';
const source=newEntity('WATER_SOURCE',0,0),v=newEntity('PIPE_VALVE',0,0),other=newEntity('PIPE_VALVE',0,0),m=newEntity('FIRE_MONITOR',0,0),cool=newEntity('TANK_COOLING',0,0);
v.facility={supplyId:source.id,open:false};other.facility={supplyId:source.id,open:false};m.facility={supplyId:v.id,open:true};cool.facility={supplyId:other.id,open:true};
const entities=[source,v,other,m,cool],net=new FacilityNetwork();net.start(entities);
assert.equal(net.states.get(m.id)?.flowing,false);net.operate(v,entities);assert.equal(net.states.get(m.id)?.flowing,true);assert.equal(net.states.get(cool.id)?.flowing,false);
net.operate(other,entities);assert.equal(net.states.get(cool.id)?.flowing,true);net.operate(v,entities);assert.equal(net.states.get(m.id)?.flowing,false);assert.equal(net.states.get(cool.id)?.flowing,true);
net.operate(v,entities);net.monitor(m.id).opening=0;net.evaluate(entities);assert.equal(net.states.get(m.id)?.flowing,false);
m.heading=90;m.position=[5,0,5];const config=defaultMonitor(),r=monitorTrajectory(m,config,[]);assert.ok(r.points.at(-1)!.x<r.points[0].x,'Heading follows scene transform');assert.ok(r.range>30);
assert.equal(behindMonitor(m,localToWorld(m,[0,0,-1.3])),true);assert.equal(behindMonitor(m,localToWorld(m,[0,0,1.3])),false);
assert.ok(monitorTrajectory(m,{...config,opening:.3},[]).range<r.range);
const tank=newEntity('TANK',0,0);tank.kind='tank';tank.radius=5;tank.height=20;tank.scale=1;tank.position=[-20,0,5];const impact=monitorTrajectory(m,config,[tank]);assert.equal(impact.hit,tank.name);assert.ok(impact.range<r.range);
assert.equal(monitorTrajectory(m,{...config,lossBar:10},[]).range,0);
// Direct manipulation is bounded by the same mechanical travel as the sliders.
const aim=defaultMonitor();
aimMonitorByDrag(aim,50,-30);
assert.equal(aim.yaw,14);assert.equal(aim.elevation,36);
aimMonitorByDrag(aim,2000,-2000);assert.equal(aim.yaw,150);assert.equal(aim.elevation,75);
aimMonitorByDrag(aim,-4000,4000);assert.equal(aim.yaw,-150);assert.equal(aim.elevation,0);
aim.opening=1;adjustMonitorOpening(aim,120);assert.equal(aim.opening,.95);
for(let i=0;i<40;i++)adjustMonitorOpening(aim,120);
assert.equal(aim.opening,0);
adjustMonitorOpening(aim,-120);assert.equal(aim.opening,.05);
assert.equal(canGripMonitor(m,localToWorld(m,[0,0,-1])),true,'rear yoke in arm reach');
assert.equal(canGripMonitor(m,localToWorld(m,[0,0,-2])),false,'distant panel operation cannot fake grasp');
assert.equal(canGripMonitor(m,localToWorld(m,[1,0,-1])),false,'side approach is not a two-hand grip');
const monitorModel=new T.Group();prepareMonitor(monitorModel,m);
const left=monitorModel.getObjectByName('MONITOR_GRIP_LEFT');
const right=monitorModel.getObjectByName('MONITOR_GRIP_RIGHT');
assert.ok(left&&right,'both operator-side handles are part of the existing monitor model');
assert.ok(left.position.x>right.position.x,'handles remain separate; both hands cannot share one point');
monitorModel.getObjectByName('MONITOR_AZIMUTH')!.rotation.y=Math.PI/3;
monitorModel.updateWorldMatrix(true,true);
assert.ok(Math.abs(left.getWorldPosition(new T.Vector3()).z-right.getWorldPosition(new T.Vector3()).z)>.1,'both handles follow yaw');
console.log('PASS: independent branches, monitor shutoff, rear control, heading, pressure response and tank impact');

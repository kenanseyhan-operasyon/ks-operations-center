import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as T from 'three';
import {JSDOM} from 'jsdom';
import {GLTFLoader} from 'three/examples/jsm/loaders/GLTFLoader.js';
import {newEntity} from '../src/scene-data';
import {NATHAN_MODEL_URL,NATHAN_PRESET} from '../src/nathan-data';
import {NathanActors} from '../src/nathan-model';
import {makeObject,applyTransform} from '../src/objects';
import {standingContact} from '../src/nathan-contact';
import {canGripMonitor} from '../src/monitor-training';

const dom=new JSDOM('<!doctype html><body/>',{url:'https://ks-3d-test.onrender.com/'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document});
const bytes=fs.readFileSync('public'+NATHAN_MODEL_URL);
const loader=new GLTFLoader();loader.register(()=>({name:'KS_HEADLESS_TEXTURE',loadTexture:async()=>new T.Texture()}));
const asset=await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'');
const operator=newEntity(NATHAN_PRESET,0,-.85);operator.heading=180;
const monitor=newEntity('FIRE_MONITOR',0,0);
const personRoot=makeObject(operator),monitorRoot=makeObject(monitor);
applyTransform(personRoot,operator);applyTransform(monitorRoot,monitor);
const actors=new NathanActors(()=>{},async()=>asset);
actors.sync([operator],new Map([[operator.id,personRoot]]));
await new Promise(r=>setTimeout(r,0));
const actor=actors.states.get(operator.id)?.actor;
assert.ok(actor&&actor.contactRig,'Real skinned Nathan IK must load');
assert.ok(canGripMonitor(monitor,operator.position),'Physical station is a valid rear-of-monitor operator position');
const left=monitorRoot.getObjectByName('MONITOR_GRIP_LEFT');
const right=monitorRoot.getObjectByName('MONITOR_GRIP_RIGHT');
assert.ok(left&&right,'Water monitor must render two real grippable handles');
const hands=[left.getWorldPosition(new T.Vector3()).toArray(),right.getWorldPosition(new T.Vector3()).toArray()] as [[number,number,number],[number,number,number]];
actor.motion('Idle');
actor.contact({...standingContact(personRoot),hands,handTangents:[[0,1,0],[0,1,0]],handsOnly:true,gripHands:true,gripRadius:.021,procedural:true,elbowPole:[0,-1,0]});
for(let i=0;i<12;i++)actor.update(.05);
const grips=actor.contactRig!.handContacts;
assert.equal(grips.filter(c=>c?.gripping).length,2,'Both Nathan hands must physically close on the monitor handles');
const gaps=grips.map(c=>c!.centre.distanceTo(c!.target));
assert.ok(gaps.every(g=>g<.10),'A visible hand must reach its physical handle, not merely have a logical grip flag: '+JSON.stringify(gaps));
actor.contact(undefined);actor.update(.05);
assert.ok(actor.contactRig!.handContacts.every(c=>!c?.gripping),'BIRAK fully releases both hands');
console.log('PASS real skinned Nathan makes and releases two reachable 3D monitor handle grips; gaps='+gaps.map(g=>g.toFixed(3)).join(','));
dom.window.close();

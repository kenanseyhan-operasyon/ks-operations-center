import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
const html=readFileSync('dist/index.html','utf8');
assert.ok(html.includes('<title>Kenan Seyhan 3D Test</title>'));
assert.ok(html.includes('href="/test.webmanifest"'));
assert.ok(html.includes('content="noindex, nofollow"'));
assert.deepEqual(JSON.parse(readFileSync('dist/cloud-config.json','utf8')),{url:'',anonKey:''},'Test build must not connect to production cloud');
const seed=readFileSync('dist/data/adb-test-seed.json'),meta=JSON.parse(readFileSync('docs/adb-test-seed.json','utf8'));
assert.equal(createHash('sha256').update(seed).digest('hex'),meta.sha256);
assert.equal(JSON.parse(seed).entities.length,meta.entities);
const manifest=JSON.parse(readFileSync('model-parts/nathan/manifest.json','utf8'));
const glb=readFileSync('dist/models/personnel/KS_Nathan_15_Hareket.glb');
assert.equal(glb.readUInt32LE(0),0x46546c67);
assert.equal(createHash('sha256').update(glb).digest('hex'),manifest.sha256);
const gltf=JSON.parse(glb.subarray(20,20+glb.readUInt32LE(12)).toString());assert.equal(gltf.animations.length,16);
const access=readFileSync('dist/models/personnel/nathan-access-animations.json');
assert.equal(createHash('sha256').update(access).digest('hex'),createHash('sha256').update(readFileSync('public/models/personnel/nathan-access-animations.json')).digest('hex'));
const imported=JSON.parse(access);assert.equal(imported.schema,1);assert.deepEqual(imported.clips.map(c=>c.name),['Climbing_Up_Ladder','Climbing_Down_Wall','Descending_Stairs']);
assert.ok(imported.sources.every(s=>/^[a-f0-9]{64}$/.test(s.sha256)));
for(const match of html.matchAll(/(?:src|href)="(\/assets\/[^"]+)"/g))assert.ok(existsSync('dist'+match[1]),match[1]);
for(const path of ['models/refueller-38k-r14.glb','textures/adb-ortho.webp','textures/adb-facility-detail.webp'])assert.ok(existsSync('dist/'+path),path);
console.log(`PASS: test HTML, PWA, empty cloud config, ${meta.entities} ADB objects, original Nathan GLB / 16 clips + 3 imported access clips, vehicle and ground assets.`);
